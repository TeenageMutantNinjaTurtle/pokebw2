// The last word of a group
static const u16 *SkipDupWords(const u16 *src) {
    return &src[2] + (src[1] - 1);
}

u16 PMSIData_GetInitialWordCode(const PMSInputData *data, u32 initial, u32 index) {
    const u16 *src = sInitialWords[initial];
    u32 i = 0;

    while (*src != PMS_WORD_END) {
        if (i == index) {
            if (*src == PMS_WORD_DUP) {
                src = SkipDupWords(src);
            }
            return *src;
        }
        if (*src == PMS_WORD_DUP) {
            src = SkipDupWords(src);
            src++;
        } else {
            src++;
        }
        i++;
    }
    return 0;
}

