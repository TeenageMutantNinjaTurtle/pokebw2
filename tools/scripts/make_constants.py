#!/usr/bin/env python3
"""Write the constant headers for moves, abilities, items, species and types, named after the game's own text, and for
sound sequences, named after the sound archive's symbols.

    make_constants.py extract/b2_us/files/a/0/0/2 include/constants --sdat extract/b2_us/files/swan_sound_data.sdat

Names are the English names in upper case, with words split at spaces, hyphens and capitals inside a word, so that
"ThunderPunch" becomes MOVE_THUNDER_PUNCH. Items named "???" are unused and get no constant. The headers only hold
#defines, so that the scripts can include them too.
"""
import argparse
import re
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from msgdata import read_archive_file  # noqa: E402

# (header, prefix, file in the system message archive, number of IDs or None for all lines, description)
TABLES = [
    ("moves.h", "MOVE", 403, None, "Moves"),
    ("abilities.h", "ABILITY", 374, None, "Abilities"),
    ("items.h", "ITEM", 64, None, "Items"),
    # The lines after the national Pokédex name eggs and other things that are not species
    ("species.h", "SPECIES", 90, 650, "Species, by national Pokédex number"),
    ("types.h", "TYPE", 398, None, "Types"),
]

# Names for the IDs whose text is not a name, or is shared with another ID. The item descriptions tell them apart.
OVERRIDES = {
    "MOVE": {0: "NONE"},
    "ABILITY": {0: "NONE"},
    "ITEM": {
        0: "NONE",
        621: "XTRANSCEIVER_MALE",
        626: "XTRANSCEIVER_FEMALE",
        628: "DNA_SPLICERS_FUSE",
        629: "DNA_SPLICERS_SEPARATE",
        636: "DROPPED_ITEM_MALE",
        637: "DROPPED_ITEM_FEMALE",
    },
    "SPECIES": {0: "NONE"},
}

# The font draws the female and male signs with these characters
CHARACTERS = {"é": "e", "⑮": "_F", "⑭": "_M"}


def identifier(name: str) -> str:
    for char, replacement in CHARACTERS.items():
        name = name.replace(char, replacement)
    name = re.sub(r"(?<=[a-z])(?=[A-Z])", "_", name)
    name = re.sub(r"['.]", "", name)
    name = re.sub(r"[^A-Za-z0-9]+", "_", name).strip("_")
    return name.upper()


def write_header(path: Path, prefix: str, names: dict[int, str], description: str):
    guard = f"POKEBW2_CONSTANTS_{path.stem.upper()}_H"
    lines = [
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        f"// {description}, generated by tools/scripts/make_constants.py from the game's text",
        "",
        *(f"#define {prefix}_{name} {i}" for i, name in names.items()),
        "",
        f"#endif // {guard}",
        "",
    ]
    path.write_text("\n".join(lines))


def sound_sequence_names(sdat: bytes) -> list[str | None]:
    """Returns the names of the sequences in a sound archive's symbol block, by sequence number."""
    symb_offset, symb_size = struct.unpack_from("<II", sdat, 0x10)
    symb = sdat[symb_offset:symb_offset + symb_size]
    record = struct.unpack_from("<I", symb, 8)[0]
    names = []
    for i in range(struct.unpack_from("<I", symb, record)[0]):
        offset = struct.unpack_from("<I", symb, record + 4 + 4 * i)[0]
        names.append(symb[offset:symb.index(b"\0", offset)].decode() if offset else None)
    return names


def write_sound_header(path: Path, sdat: bytes):
    guard = "POKEBW2_CONSTANTS_SOUND_H"
    lines = [f"#ifndef {guard}", f"#define {guard}", "",
             "// Sound sequences, with the names that the sound archive's symbols give them, generated by",
             "// tools/scripts/make_constants.py", ""]
    lines += [f"#define {name} {i:#x}" for i, name in enumerate(sound_sequence_names(sdat)) if name]
    lines += ["", f"#endif // {guard}", ""]
    path.write_text("\n".join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("archive", type=Path, help="the system message archive, files/a/0/0/2")
    parser.add_argument("output", type=Path, help="the directory for the headers")
    parser.add_argument("--sdat", type=Path, help="the sound archive, files/swan_sound_data.sdat, for sound.h")
    args = parser.parse_args()
    if args.sdat:
        write_sound_header(args.output / "sound.h", args.sdat.read_bytes())

    for header, prefix, file, count, description in TABLES:
        lines = read_archive_file(args.archive, file)[:count]
        overrides = OVERRIDES.get(prefix, {})
        names = {}
        for i, text in enumerate(lines):
            if i in overrides:
                names[i] = overrides[i]
            elif text != "???":
                names[i] = identifier(text)
        seen = {}
        for i, name in names.items():
            if name in seen:
                sys.exit(f"{prefix}_{name} is both {seen[name]} and {i}, add an override")
            seen[name] = i
        write_header(args.output / header, prefix, names, description)


if __name__ == "__main__":
    main()
